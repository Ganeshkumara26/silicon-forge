@dataclass(frozen=True)
class PhysicalDerivationRecord:
    """Trace record for each derived parameter."""

    name: str
    value: float | int | str
    unit: str
    source_equation: str
    source_value: float
    comment: str


def _sv_header(title: str, timescale: str = "1ns/1ps") -> list[str]:
    """Generate standard SystemVerilog header."""
    return [
        f"`timescale {timescale}",
        "`default_nettype none",
        f"// {title}",
        "// Generated by siliconforge RTL generator",
        "// See guidebook Chapter 12 for derivation requirements",
        "",
    ]


def generate_aac_fsm(parameters: AACParameters, derivation_records: Sequence[PhysicalDerivationRecord]) -> str:
    """Generate AAC SystemVerilog module with physical derivation comments.

    From guidebook Chapter 16.1
    """
    sv_lines = [
        "// Generated by siliconforge RTL generator",
        "// Every constant below has a physical derivation trace",
        "// See chapter 11 of the guidebook for derivation methodology",
        "",
        f"// WAIT_CYCLES = {parameters.min_wait_cycles} derived from tank Q={parameters.tank_q:.1f}",
        f"// Eq: Wait_cycles = ceil(t_settle / T_ref) where t_settle = 3 * tau_env",
        f"// tau_env = 2*Q/omega0 = {parameters.settling_time_constant_s*1e12:.2f} ps",
        "",
        "module aac_core (",
        "    input  logic clk,",
        "    input  logic rst_n,",
        "    input  logic enable,",
        "    input  logic amp_low,",
        "    input  logic amp_high,",
        "    output logic [3:0] dac_code,",
        "    output logic aac_locked",
        ");",
        "",
        f"    localparam integer WAIT_CYCLES = {parameters.min_wait_cycles};",
        "    localparam integer DEBOUNCE_LIMIT = 3;  // Prevents chattering",
        "",
        "    typedef enum logic [1:0] {IDLE, WAIT, SAMPLE, UPDATE} state_t;",
        "",
        "    state_t state, next_state;",
        "    logic [2:0] wait_cnt;",
        "    logic [1:0] debounce_cnt;",
        "",
        "    // FSM logic",
        "    always_ff @(posedge clk or negedge rst_n) begin",
        "        if (!rst_n) begin",
        "            state <= IDLE;",
        "            wait_cnt <= 0;",
        "            debounce_cnt <= 0;",
        "        end else begin",
        "            case (state)",
        "                IDLE: begin",
        "                    if (enable) state <= WAIT;",
        "                end",
        "                WAIT: begin",
        "                    if (wait_cnt >= WAIT_CYCLES) begin",
        "                        wait_cnt <= 0;",
        "                        state <= SAMPLE;",
        "                    end else begin",
        "                        wait_cnt <= wait_cnt + 1;",
        "                    end",
        "                end",
        "                SAMPLE: begin",
        "                    if (amp_low && debounce_cnt < DEBOUNCE_LIMIT) begin",
        "                        debounce_cnt <= debounce_cnt + 1;",
        "                    end else if (amp_high && debounce_cnt > 0) begin",
        "                        debounce_cnt <= debounce_cnt - 1;",
        "                    end",
        "                    state <= UPDATE;",
        "                end",
        "                UPDATE: begin",
        "                    // Increment/decrement dac_code based on amp flags",
        "                    if (debounce_cnt >= DEBOUNCE_LIMIT) begin",
        "                        dac_code <= dac_code + 1;",
        "                        debounce_cnt <= 0;",
        "                    end else if (debounce_cnt == 0 && amp_high) begin",
        "                        dac_code <= dac_code - 1;",
        "                    end",
        "                    state <= WAIT;",
        "                end",
        "            endcase",
        "        end",
        "    end",
        "",
        "    assign aac_locked = (dac_code inside {0,3}, {2,3});  // Based on 600-800mV target window",
        "endmodule",
    ]

    return "\n".join(sv_lines)


def generate_afc_fsm(parameters: AFCParameters, derivation_records: Sequence[PhysicalDerivationRecord]) -> str:
    """Generate AFC binary search SystemVerilog module.

    From guidebook Chapter 16.2
    """
    n_bits = parameters.n_bits
    target_count = 64  # From guidebook: 64 reference cycles for 1.5% resolution

    sv_lines = [
        "// Generated by siliconforge RTL generator",
        "// AFC binary search derived from physical oscillator characteristics",
        "",
        f"// CAP_WIDTH = {n_bits} derived from total drift = {parameters.total_drift_hz/1e6:.1f} MHz",
        f"// C_LSB = {parameters.c_lsb_f*1e15:.1f} fF computed from frequency equation",
        f"// Search mode: {parameters.search_mode} (monotonicity verified)",
        "",
        "module afc_core (",
        "    input  logic clk_ref,     // 50 MHz reference",
        "    input  logic clk_vco,     // 50 MHz divided VCO (after CML /5)",
        "    input  logic rst_n,",
        "    input  logic enable,",
        f"    output logic [{n_bits-1}:0] cap_code,",
        "    output logic afc_locked",
        ");",
        "",
        f"    localparam integer CAP_BITS = {n_bits};",
        f"    localparam integer TARGET_COUNT = {target_count};",
        "",
        "    typedef enum logic [1:0] {IDLE, COUNT, COMPARE, NEXT_BIT} state_t;",
        "",
        "    state_t state;",
        f"    logic [{n_bits-1}:0] current_code;",
        "    logic [6:0] vco_cnt;",
        "    logic [6:0] ref_cnt;",
        "    logic [2:0] bit_index;",
        "",
        "    // Binary search FSM",
        "    always_ff @(posedge clk_ref or negedge rst_n) begin",
        "        if (!rst_n) begin",
        "            state <= IDLE;",
        "            cap_code <= 0;",
        "            vco_cnt <= 0;",
        "            ref_cnt <= 0;",
        "        end else begin",
        "            case (state)",
        "                IDLE: begin",
        "                    if (enable) begin",
        "                        current_code <= 0;",
        "                        bit_index <= CAP_BITS - 1;",
        "                        vco_cnt <= 0;",
        "                        ref_cnt <= 0;",
        "                        state <= COUNT;",
        "                    end",
        "                end",
        "                COUNT: begin",
        "                    if (ref_cnt < TARGET_COUNT - 1) begin",
        "                        ref_cnt <= ref_cnt + 1;",
        "                        if (clk_vco) vco_cnt <= vco_cnt + 1;",
        "                    end else begin",
        "                        state <= COMPARE;",
        "                    end",
        "                end",
        "                COMPARE: begin",
        "                    // Binary search decision",
        "                    if (vco_cnt < TARGET_COUNT)",
        "                        current_code[bit_index] <= 1;",
        "                    // else keep bit at 0",
        "                    ",
        "                    if (bit_index == 0) begin",
        "                        cap_code <= current_code;",
        "                        state <= IDLE;",
        "                    end else begin",
        "                        bit_index <= bit_index - 1;",
        "                        vco_cnt <= 0;",
        "                        ref_cnt <= 0;",
        "                    end",
        "                end",
        "            endcase",
        "        end",
        "    end",
        "",
        f"    assign afc_locked = (state == IDLE) && (enable == 0);",
        "endmodule",
    ]

    return "\n".join(sv_lines)


def generate_master_controller(
    aac_params: AACParameters,
    afc_params: AFCParameters,
) -> str:
    """Generate master boot sequence controller.

    From guidebook Chapter 16.3
    Implements: Kickstart -> AAC -> AFC -> PLL Lock
    """
    sv_lines = [
        "// Generated by siliconforge RTL generator",
        "// Master boot sequence enforces analog-first startup",
        "",
        "module system_controller (",
        "    input  logic clk,",
        "    input  logic rst_n,",
        "    input  logic amp_low,",
        "    input  logic amp_high,",
        "    input  logic startup_timer_done,",
        "    output logic [3:0] master_dac_code,",
        f"    output logic [{afc_params.n_bits-1}:0] cap_code,",
        "    output logic aac_enable,",
        "    output logic afc_enable,",
        "    output logic pll_enable",
        ");",
        "",
        f"    // Startup timer derived from AAC wait cycles * 2",
        f"    // Kickstart period: {aac_params.min_wait_cycles * 2} reference cycles",
        "",
        "    typedef enum logic [2:0] {",
        "        ST_RESET,",
        "        ST_KICKSTART,",
        "        ST_AAC_CAL,",
        "        ST_AFC_CAL,",
        "        ST_PLL_LOCK",
        "    } sys_state_t;",
        "",
        "    sys_state_t state;",
        "    logic [3:0] kickstart_dac;  // Max current for startup",
        "",
        "    // State register",
        "    always_ff @(posedge clk or negedge rst_n) begin",
        "        if (!rst_n) begin",
        "            state <= ST_RESET;",
        "            kickstart_dac <= 4'b1111;  // Forced maximum for SS_hot startup",
        "        end else begin",
        "            case (state)",
        "                ST_RESET: begin",
        "                    state <= ST_KICKSTART;",
        "                end",
        "                ST_KICKSTART: begin",
        "                    // Hold kickstart until timer expires",
        "                    if (startup_timer_done)",
        "                        state <= ST_AAC_CAL;",
        "                end",
        "                ST_AAC_CAL: begin",
        "                    // Wait for AAC to converge (amp flags stable)",
        "                    if (amp_low == 0 && amp_high == 0)",
        "                        state <= ST_AFC_CAL;",
        "                end",
        "                ST_AFC_CAL: begin",
        "                    // Execute AFC binary search, then transition to PLL",
        "                    state <= ST_PLL_LOCK;",
        "                end",
        "                ST_PLL_LOCK: begin",
        "                    // PLL locked - done",
        "                end",
        "            endcase",
        "        end",
        "    end",
        "",
        "    // Output assignments",
        "    always_comb begin",
        "        case (state)",
        "            ST_RESET, ST_KICKSTART: begin",
        "                master_dac_code = kickstart_dac;",
        "                aac_enable = 0;",
        "                afc_enable = 0;",
        "                pll_enable = 0;",
        "            end",
        "            ST_AAC_CAL: begin",
        "                aac_enable = 1;",
        "                afc_enable = 0;",
        "                pll_enable = 0;",
        "            end",
        "            ST_AFC_CAL, ST_PLL_LOCK: begin",
        "                aac_enable = 0;  // Freeze for AFC",
        "                afc_enable = 1;",
        "                pll_enable = 0;",
        "            end",
        "            default: begin",
        "                master_dac_code = 0;",
        "                aac_enable = 0;",
        "                afc_enable = 0;",
        "                pll_enable = 0;",
        "            end",
        "        endcase",
        "    end",
        "",
        "endmodule",
    ]

    return "\n".join(sv_lines)


def generate_sdc_constraints(
    vco_sizing: VCOComponentSizing,
    i_cp_a: float,
) -> str:
    """Generate SDC constraints for synthesis.

    From guidebook Chapter 18.1
    """
    clk_period_ns = 1.0 / 50e6 * 1e9

    lines = [
        "# SDC Constraints for digitally-assisted PLL",
        "# Generated by siliconforge RTL generator",
        f"# VCO frequency: {vco_sizing.frequency_hz/1e9:.2f} GHz",
        f"# Charge pump current: {i_cp_a*1e6:.1f} uA",
        "",
        f"create_clock -name clk_ref -period {clk_period_ns:.3f} [get_ports clk_ref]",
        "# High-speed clock for N-divider (2.05 GHz after CML /5)",
        "create_clock -name clk_2G -period 0.487 [get_ports clk_2G]",
        "",
        "# Clock uncertainty for 130nm",
        "set_clock_uncertainty 0.5 [get_clocks clk_ref]",
        "set_clock_uncertainty 0.05 [get_clocks clk_2G]",
        "",
        "# Input delay for analog comparators (~2ns delay)",
        "set_input_delay -max 2.0 -clock clk_ref [get_ports amp_low]",
        "set_input_delay -max 2.0 -clock clk_ref [get_ports amp_high]",
        "",
        "# Output delay for DAC control signals (~1.5ns propagation)",
        "set_output_delay -max 1.5 -clock clk_ref [get_ports dac_code*]",
    ]

    return "\n".join(lines)


def generate_charge_pump_fsm(
    params: ChargePumpParameters,
    derivation_records: Sequence[PhysicalDerivationRecord],
) -> str:
    """Generate charge pump SystemVerilog module.

    From guidebook Chapter 15.4: I_CP must exceed varactor leakage
    by at least 20dB margin for phase offset < 0.01 rad.
    """
    sv_lines = _sv_header("Charge Pump Controller")

    sv_lines.extend([
        f"// I_CP = {params.i_cp_a*1e6:.2f} uA from varactor_leakage {params.varactor_leakage_a*1e12:.2f} pA",
        f"// delta_phi_target = {params.phase_offset_target:.3f} rad",
        "",
        "module charge_pump (",
        "    input  logic clk_ref,",
        "    input  logic clk_vco,",
        "    input  logic rst_n,",
        "    input  logic up,",
        "    input  logic down,",
        "    output logic cp_p,",
        "    output logic cp_n",
        ");",
        "",
        "    // Up/down current steering",
        "    always_comb begin",
        "        cp_p = up;",
        "        cp_n = down;",
        "    end",
        "endmodule",
    ])

    return "\n".join(sv_lines)


